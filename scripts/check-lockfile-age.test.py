#!/usr/bin/env python3
"""Runs check-lockfile-age.py as a subprocess against throwaway git repos.

The registry is a local HTTP server that answers in npm's packument shape, so every case is
deterministic. With GUARD_LIVE_REGISTRIES=1 one more case runs against the real npm, to prove
that shape still holds.

Run: python3 scripts/check-lockfile-age.test.py
"""

import json
import os
import subprocess
import sys
import tempfile
import threading
import unittest
import urllib.parse
from datetime import datetime, timedelta, timezone
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path

SCRIPT = Path(__file__).with_name('check-lockfile-age.py')

# The user's own git config (hooks, signing, identity includes) stays out of the throwaway repos.
GIT_ENV = {**os.environ, 'GIT_CONFIG_GLOBAL': os.devnull, 'GIT_CONFIG_NOSYSTEM': '1'}

HEADER = '# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n'


def hours_ago(hours):
    return (datetime.now(timezone.utc) - timedelta(hours=hours)).strftime('%Y-%m-%dT%H:%M:%S.000Z')


def block(key, version, resolved=True, name=None, dependencies=None):
    """One yarn 1 lockfile entry. `name` is the package the tarball belongs to, if not the key's."""
    if name is None:
        name = key.split(',')[0].strip('"').rsplit('@', 1)[0]
    base = name.rsplit('/', 1)[-1]
    lines = [f'{key}:', f'  version "{version}"']
    if resolved is True:
        lines.append(f'  resolved "https://registry.yarnpkg.com/{name}/-/{base}-{version}.tgz#0123abcd"')
        lines.append('  integrity sha512-AAAA==')
    elif resolved:
        lines.append(f'  resolved "{resolved}"')
    if dependencies:
        lines.append('  dependencies:')
        lines += [f'    {dep} "{rng}"' for dep, rng in dependencies.items()]
    return '\n'.join(lines) + '\n'


def lockfile(*blocks):
    return HEADER + '\n'.join(blocks)


class FakeRegistry:
    """Answers GET requests from a path -> (status, JSON body) table and records each path."""

    def __init__(self):
        self.routes = {}
        self.requested = []
        self.truncate = set()
        registry = self

        class Handler(BaseHTTPRequestHandler):
            def do_GET(self):
                registry.requested.append(self.path)
                status, body = registry.routes.get(self.path, (404, {'error': 'not found'}))
                payload = json.dumps(body).encode()
                self.send_response(status)
                self.send_header('Content-Type', 'application/json')
                self.send_header('Content-Length', str(len(payload) + (100 if self.path in registry.truncate else 0)))
                self.end_headers()
                self.wfile.write(payload)

            def log_message(self, *args):
                pass

        self.server = ThreadingHTTPServer(('127.0.0.1', 0), Handler)
        threading.Thread(target=self.server.serve_forever, daemon=True).start()
        self.base = f'http://127.0.0.1:{self.server.server_port}'

    def npm(self, name, **versions_hours_ago):
        """A packument whose `time` holds each version, published that many hours ago."""
        times = {'created': hours_ago(9000), 'modified': hours_ago(0)}
        times.update({v.replace('_', '.'): hours_ago(h) for v, h in versions_hours_ago.items()})
        self.routes[f"/{urllib.parse.quote(name, safe='@')}"] = (200, {'name': name, 'time': times})


def make_repo(root, base_files, head_files):
    """A repo whose HEAD~1 holds base_files and HEAD holds head_files."""
    repo = Path(tempfile.mkdtemp(dir=root))

    def commit(files, message):
        for path, content in files.items():
            target = repo / path
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content)
        subprocess.run(['git', 'add', '-A'], cwd=repo, check=True, env=GIT_ENV)
        subprocess.run(['git', '-c', 'user.name=test', '-c', 'user.email=test@example.invalid',
                        'commit', '-q', '--allow-empty', '-m', message], cwd=repo, check=True, env=GIT_ENV)

    subprocess.run(['git', 'init', '-q', str(repo)], check=True, env=GIT_ENV)
    commit(base_files, 'base')
    commit(head_files, 'head')
    return repo


class LockfileAgeCheck(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.tmp = tempfile.TemporaryDirectory()
        cls.registry = FakeRegistry()

    @classmethod
    def tearDownClass(cls):
        cls.registry.server.shutdown()
        cls.tmp.cleanup()

    def setUp(self):
        self.registry.routes.clear()
        self.registry.requested.clear()
        self.registry.truncate.clear()

    def run_check(self, base, head, extra_env=None, registry=None):
        repo = make_repo(self.tmp.name, base, head)
        env = {**GIT_ENV, 'GUARD_NPM_REGISTRY': registry or self.registry.base, **(extra_env or {})}
        result = subprocess.run([sys.executable, str(SCRIPT), 'HEAD~1', 'HEAD'], cwd=repo, env=env,
                                capture_output=True, text=True, timeout=120)
        return result.returncode, result.stdout, result.stderr

    def test_a_repo_without_a_yarn_lock_passes_and_reads_nothing(self):
        code, out, err = self.run_check({'README.md': 'a'}, {'README.md': 'b', 'package-lock.json': '{}'})
        self.assertEqual(code, 0, err)
        self.assertIn('0 added versions, 0 read from npm, 0 findings', out)
        self.assertEqual(self.registry.requested, [])

    def test_an_unchanged_lockfile_reads_nothing(self):
        lock = lockfile(block('knip@^6.41.0', '6.48.0'))
        code, out, err = self.run_check({'yarn.lock': lock}, {'yarn.lock': lock, 'README.md': 'x'})
        self.assertEqual(code, 0, err)
        self.assertIn('0 added versions', out)
        self.assertEqual(self.registry.requested, [])

    def test_a_young_version_fails_and_says_when_it_clears(self):
        self.registry.npm('knip', **{'6_45_1': 900, '6_48_0': 25})
        code, _, err = self.run_check(
            {'yarn.lock': lockfile(block('knip@^6.41.0', '6.45.1'))},
            {'yarn.lock': lockfile(block('knip@^6.41.0', '6.48.0'))})
        self.assertEqual(code, 1)
        self.assertRegex(err, r'yarn.lock: knip@6\.48\.0 was published \d{4}-\d\d-\d\d \d\d:\d\d UTC, 25 hours ago; '
                              r'it is 72 hours old at \d{4}-\d\d-\d\d \d\d:\d\d UTC')
        self.assertIn('Every version is 72 hours old at', err)
        self.assertEqual(self.registry.requested, ['/knip'])

    def test_the_age_floor_is_72_hours(self):
        self.registry.npm('just-old-enough', **{'1_0_0': 72.05})
        self.registry.npm('one-hour-short', **{'1_0_0': 71})
        code, _, err = self.run_check(
            {'yarn.lock': lockfile()},
            {'yarn.lock': lockfile(block('just-old-enough@^1', '1.0.0'), block('one-hour-short@^1', '1.0.0'))})
        self.assertEqual(code, 1)
        self.assertIn('one-hour-short@1.0.0 was published', err)
        self.assertNotIn('just-old-enough', err)

    def test_a_dependency_of_a_dependency_is_checked(self):
        # The unbash case: a version no manifest names, brought in by refreshing the tree above it.
        self.registry.npm('knip', **{'6_45_1': 900})
        self.registry.npm('unbash', **{'6_0_4': 900, '6_0_5': 37})
        base = lockfile(block('knip@^6.41.0', '6.45.1', dependencies={'unbash': '^6.0.0'}), block('unbash@^6.0.0', '6.0.4'))
        head = lockfile(block('knip@^6.41.0', '6.45.1', dependencies={'unbash': '^6.0.0'}), block('unbash@^6.0.0', '6.0.5'))
        code, out, err = self.run_check({'yarn.lock': base}, {'yarn.lock': head})
        self.assertEqual(code, 1)
        self.assertIn('unbash@6.0.5 was published', err)
        self.assertIn('1 added versions, 1 read from npm, 1 findings', out)

    def test_an_old_enough_bump_passes(self):
        self.registry.npm('@types/node', **{'22_20_4': 2000, '22_20_5': 100})
        code, out, err = self.run_check(
            {'yarn.lock': lockfile(block('"@types/node@^22"', '22.20.4'))},
            {'yarn.lock': lockfile(block('"@types/node@^22", "@types/node@^22.1"', '22.20.5'))})
        self.assertEqual(code, 0, err)
        self.assertIn('1 added versions, 1 read from npm, 0 findings', out)
        self.assertEqual(self.registry.requested, ['/@types%2Fnode'])

    def test_a_scoped_name_comes_from_the_tarball_url(self):
        self.registry.npm('@eslint-community/regexpp', **{'4_12_3': 10})
        code, _, err = self.run_check(
            {'yarn.lock': lockfile()},
            {'yarn.lock': lockfile(block('"@eslint-community/regexpp@^4.12.1"', '4.12.3'))})
        self.assertEqual(code, 1)
        self.assertIn('yarn.lock: @eslint-community/regexpp@4.12.3 was published', err)

    def test_an_npm_alias_is_read_as_the_package_it_installs(self):
        self.registry.npm('string-width', **{'4_2_3': 5})
        code, _, err = self.run_check(
            {'yarn.lock': lockfile()},
            {'yarn.lock': lockfile(block('"string-width-cjs@npm:string-width@^4.2.0"', '4.2.3', name='string-width'))})
        self.assertEqual(code, 1)
        self.assertIn('string-width@4.2.3 was published', err)
        self.assertEqual(self.registry.requested, ['/string-width'])

    def test_an_entry_without_a_resolved_line_is_still_checked(self):
        self.registry.npm('vite', **{'8_2_2': 3})
        code, _, err = self.run_check(
            {'yarn.lock': lockfile()},
            {'yarn.lock': lockfile(block('vite@^8.0.0', '8.2.2', resolved=False))})
        self.assertEqual(code, 1)
        self.assertIn('vite@8.2.2 was published', err)

    def test_a_local_sibling_is_not_read(self):
        code, out, err = self.run_check(
            {'yarn.lock': lockfile()},
            {'yarn.lock': lockfile(block('"shared-types@file:../shared-types"', '0.1.0', resolved=False),
                                   block('"other@link:../other"', '1.0.0', resolved='link:../other'))})
        self.assertEqual(code, 0, err)
        self.assertIn('0 added versions', out)
        self.assertEqual(self.registry.requested, [])

    def test_a_tarball_from_another_host_is_named_and_not_failed(self):
        code, out, err = self.run_check(
            {'yarn.lock': lockfile()},
            {'yarn.lock': lockfile(block('forked@^1', '1.0.0', resolved='https://tarballs.example.invalid/forked-1.0.0.tgz'))})
        self.assertEqual(code, 0, err)
        self.assertIn('yarn.lock: forked@1.0.0 comes from tarballs.example.invalid, not from npm; its age is not checked', out)
        self.assertEqual(self.registry.requested, [])

    def test_every_yarn_lock_in_the_tree_is_read_and_node_modules_is_skipped(self):
        self.registry.npm('young', **{'1_0_0': 1})
        head = lockfile(block('young@^1', '1.0.0'))
        code, _, err = self.run_check(
            {'README.md': 'a'},
            {'packages/web/yarn.lock': head, 'node_modules/dep/yarn.lock': head})
        self.assertEqual(code, 1)
        self.assertIn('packages/web/yarn.lock: young@1.0.0 was published', err)
        self.assertNotIn('node_modules', err)

    def test_the_first_block_after_the_header_is_read(self):
        self.registry.npm('aaa', **{'1_0_0': 1})
        self.registry.npm('bbb', **{'1_0_0': 1})
        code, _, err = self.run_check(
            {'yarn.lock': lockfile()},
            {'yarn.lock': lockfile(block('aaa@^1', '1.0.0'), block('bbb@^1', '1.0.0'))})
        self.assertEqual(code, 1)
        self.assertIn('aaa@1.0.0 was published', err)
        self.assertIn('bbb@1.0.0 was published', err)

    def test_a_berry_lockfile_is_named_and_not_read(self):
        berry = '__metadata:\n  version: 8\n\n"knip@npm:^6.41.0":\n  version: 6.48.0\n'
        code, out, err = self.run_check({'README.md': 'a'}, {'yarn.lock': berry})
        self.assertEqual(code, 0, err)
        self.assertIn('yarn.lock: not a yarn 1 lockfile, not read', out)

    def test_a_package_npm_does_not_know_fails(self):
        code, _, err = self.run_check({'yarn.lock': lockfile()}, {'yarn.lock': lockfile(block('ghost@^1', '1.0.0'))})
        self.assertEqual(code, 1)
        self.assertIn('yarn.lock: ghost does not exist on npm (read without a token)', err)

    def test_an_unpublished_package_fails_by_name(self):
        self.registry.routes['/gone'] = (200, {'name': 'gone', 'time': {'created': hours_ago(900), 'unpublished': {'time': hours_ago(10)}}})
        code, _, err = self.run_check({'yarn.lock': lockfile()}, {'yarn.lock': lockfile(block('gone@^1', '1.0.0'))})
        self.assertEqual(code, 1)
        self.assertIn('npm gives no publish time for gone@1.0.0', err)

    def test_a_finding_that_waiting_cannot_clear_drops_the_wait_hint(self):
        self.registry.npm('young', **{'1_0_0': 1})
        code, _, err = self.run_check(
            {'yarn.lock': lockfile()}, {'yarn.lock': lockfile(block('young@^1', '1.0.0'), block('ghost@^1', '1.0.0'))})
        self.assertEqual(code, 1)
        self.assertIn('young@1.0.0 was published', err)
        self.assertNotIn('A re-run of this job after that time passes', err)

    def test_a_body_cut_short_is_retried_and_exit_2(self):
        self.registry.npm('knip', **{'6_48_0': 900})
        self.registry.truncate.add('/knip')
        code, _, err = self.run_check({'yarn.lock': lockfile()}, {'yarn.lock': lockfile(block('knip@^6', '6.48.0'))})
        self.assertEqual(code, 2)
        self.assertNotIn('Traceback', err)
        self.assertEqual(self.registry.requested, ['/knip'] * 3)

    def test_a_version_npm_gives_no_time_for_fails(self):
        self.registry.npm('knip', **{'6_45_1': 900})
        code, _, err = self.run_check({'yarn.lock': lockfile()}, {'yarn.lock': lockfile(block('knip@^6', '6.99.0'))})
        self.assertEqual(code, 1)
        self.assertIn('npm gives no publish time for knip@6.99.0', err)

    def test_a_registry_error_is_exit_2_never_a_pass(self):
        self.registry.routes['/knip'] = (500, {'error': 'boom'})
        code, _, err = self.run_check({'yarn.lock': lockfile()}, {'yarn.lock': lockfile(block('knip@^6', '6.48.0'))})
        self.assertEqual(code, 2)
        self.assertIn('HTTP 500', err)
        self.assertEqual(self.registry.requested, ['/knip'] * 3)

    @unittest.skipUnless(os.environ.get('GUARD_LIVE_REGISTRIES') == '1', 'set GUARD_LIVE_REGISTRIES=1 to reach npm')
    def test_the_real_npm_answers_in_the_shape_read(self):
        # left-pad 1.3.0 was published in 2018 and is far past the floor.
        code, out, err = self.run_check(
            {'yarn.lock': lockfile()}, {'yarn.lock': lockfile(block('left-pad@^1.3.0', '1.3.0'))},
            registry='https://registry.npmjs.org')
        self.assertEqual(code, 0, err)
        self.assertIn('1 added versions, 1 read from npm, 0 findings', out)


if __name__ == '__main__':
    unittest.main()
